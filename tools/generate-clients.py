#!/usr/bin/env python3
"""Reproducible clients for this contract's JSON Schema subset; no network access."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
raw = (ROOT / "openapi/rescrow-v1.json").read_bytes()
spec = json.loads(raw)
version = hashlib.sha256(raw).hexdigest()

py_inline = []
inline_count = 0


def typ(s, lang, name=None):
    global inline_count
    if "$ref" in s:
        return s["$ref"].split("/")[-1]
    if "const" in s:
        return literal([s["const"]], lang)
    if "enum" in s:
        return literal(s["enum"], lang)
    for key in ["anyOf", "oneOf"]:
        if key in s:
            return " | ".join(typ(v, lang) for v in s[key])
    kind = s.get("type")
    if kind == "null":
        return "None" if lang == "py" else "null"
    if kind == "string":
        return "str" if lang == "py" else "string"
    if kind == "integer":
        return "int" if lang == "py" else "number"
    if kind == "boolean":
        return "bool" if lang == "py" else "boolean"
    if kind == "array":
        item = typ(s["items"], lang)
        return f"list[{item}]" if lang == "py" else f"Array<{item}>"
    if kind == "object":
        if "properties" not in s:
            return (
                f'dict[str, {typ(s["additionalProperties"],lang)}]'
                if lang == "py"
                else f'Record<string, {typ(s["additionalProperties"],lang)}>'
            )
        if lang == "py":
            inline_count += 1
            typename = name or f"_Inline{inline_count}"
            fields = []
            for key, value in s["properties"].items():
                field = typ(value, lang)
                if key not in s["required"]:
                    field = f"NotRequired[{field}]"
                fields.append(f"    {key}: {field}\n")
            py_inline.append(
                f"class {typename}(TypedDict):\n"
                + ("".join(fields) or "    pass\n")
                + "\n"
            )
            return typename
        return (
            "{ "
            + "; ".join(
                json.dumps(k)
                + ("" if k in s["required"] else "?")
                + ": "
                + typ(v, lang)
                for k, v in s["properties"].items()
            )
            + " }"
        )
    raise ValueError(f"Unsupported schema: {s}")


def literal(values, lang):
    if lang == "py":
        return "Literal[" + ", ".join(repr(v) for v in values) + "]"
    return " | ".join(json.dumps(v) for v in values)


py = f"""# Generated by tools/generate-clients.py; contract sha256:{version}
from __future__ import annotations
from typing import TypedDict, NotRequired, Literal, cast
from transport import Transport, new_id, path_id, ProblemError

"""
ts = f"""// Generated by tools/generate-clients.py; contract sha256:{version}
import {{ Transport, pathId }} from './transport.ts';
export {{ newId, ProblemError }} from './transport.ts';

"""
for name, schema in spec["components"]["schemas"].items():
    py_inline.clear()
    result = typ(schema, "py", name)
    py += "".join(py_inline)
    if result != name:
        py += f"{name} = {result}\n"
    ts += f'export type {name} = {typ(schema,"ts")};\n'
py += """
class Client(Transport):
"""
ts += """
export class Client extends Transport {
"""
for path, entry in spec["paths"].items():
    for method, op in entry.items():
        name = op["operationId"]
        out = op["x-response-schema"]
        args = []
        tsargs = []
        body = "None"
        tsbody = "undefined"
        key = "None"
        tskey = "undefined"
        query = "None"
        tsquery = "undefined"
        if "{id}" in path:
            args += ["id: str"]
            tsargs += ["id: string"]
        if "requestBody" in op:
            schema = op["requestBody"]["content"]["application/json"]["schema"]
            typename = typ(schema, "py")
            optional = not op["requestBody"]["required"]
            args += [f"body: {typename}" + (" | None = None" if optional else "")]
            tsargs += [f"body" + ("?" if optional else "") + f": {typename}"]
            body = "body"
            tsbody = "body"
        if name == "prepare":
            args += ["*, idempotency_key: str"]
            tsargs += ["idempotencyKey: string"]
            key = "idempotency_key"
            tskey = "idempotencyKey"
        if name.startswith("list"):
            args += ["query: dict[str, str | int] | None = None"]
            tsargs += ["query?: Record<string, string | number>"]
            query = "query"
            tsquery = "query"
        identity = "id" if "/reservations/{id}" in path else "None"
        tsidentity = "id" if "/reservations/{id}" in path else "undefined"
        pypath = (
            "f" + repr(path.replace("{id}", "{path_id(id)}"))
            if "{id}" in path
            else repr(path)
        )
        tspath = "`" + path.replace("{id}", "${pathId(id)}") + "`"
        py += f'    def {name}(self, {", ".join(args)}) -> {out}:\n        return cast({out}, self.request({method.upper()!r}, {pypath}, {body}, {key}, {query}, {identity}))\n\n'
        ts += f'  async {name}({", ".join(tsargs)}): Promise<{out}> {{\n    return this.request({json.dumps(method.upper())}, {tspath}, {tsbody}, {tskey}, {tsquery}, {tsidentity}) as Promise<{out}>;\n  }}\n'
ts += "}\n"
(ROOT / "clients/python/rescrow_client.py").write_text(py.rstrip() + "\n")
(ROOT / "clients/typescript/rescrow_client.ts").write_text(ts.rstrip() + "\n")
